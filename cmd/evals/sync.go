const generatedHeader = "# Generated by `go run ./cmd/evals sync` from task.toml and the starting project; do not edit.\n"

// conditionMarker is the line of a task's environment/Dockerfile that the
// runner replaces with the agent aids of a condition.
const conditionMarker = "RUN project-setup finish"

func cmdSync(args []string) error {
	fs := flag.NewFlagSet("sync", flag.ExitOnError)
	root := fs.String("root", "", "the evals directory")
	check := fs.Bool("check", false, "report stale generated files instead of writing them (exit 1)")
	_ = fs.Parse(args)
	dir, err := evalsRoot(*root)
	if err != nil {
		return err
	}
	stale, err := syncTasks(dir, *check)
	if err != nil {
		return err
	}
	if *check && len(stale) > 0 {
		return exitError{1, "stale generated files (run `go run ./cmd/evals sync`):\n  " + strings.Join(stale, "\n  ")}
	}
	return nil
}

// syncTasks writes (or, with check, compares) every task's generated files.
func syncTasks(evalsDir string, check bool) ([]string, error) {
	tasks, err := spec.LoadTasks(filepath.Join(evalsDir, "tasks"))
	if err != nil {
		return nil, err
	}
	var stale []string
	for _, t := range tasks {
		if _, err := spec.LoadVerify(filepath.Join(t.Dir, "tests", "verify.toml")); err != nil {
			return nil, err
		}
		if t.PlainDir != "" {
			v, err := spec.LoadVerify(filepath.Join(t.PlainDir, "tests", "verify.toml"))
			if err != nil {
				return nil, err
			}
			if !v.CommandMode() {
				return nil, fmt.Errorf("tasks/%s/plain/tests/verify.toml: mode must be \"command\" (tests without axx)", t.ID())
			}
		}
		files, err := generated(evalsDir, t)
		if err != nil {
			return nil, err
		}
		paths := make([]string, 0, len(files))
		for p := range files {
			paths = append(paths, p)
		}
		sort.Strings(paths)
		for _, rel := range paths {
			want := files[rel]
			p := filepath.Join(t.Dir, filepath.FromSlash(rel))
			have, err := os.ReadFile(p)
			switch {
			case want == nil && errors.Is(err, os.ErrNotExist):
				continue
			case want == nil:
				if check {
					stale = append(stale, filepath.Join("tasks", t.ID(), rel)+" (should not exist)")
				} else if err := os.Remove(p); err != nil {
					return nil, err
				}
				continue
			case err == nil && bytes.Equal(have, want):
				continue
			}
			if check {
				stale = append(stale, filepath.Join("tasks", t.ID(), rel))
				continue
			}
			if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
				return nil, err
			}
			mode := os.FileMode(0o644)
			if strings.HasSuffix(rel, ".sh") {
				mode = 0o755
			}
			if err := os.WriteFile(p, want, mode); err != nil {
				return nil, err
			}
			_ = os.Chmod(p, mode)
			fmt.Printf("wrote tasks/%s/%s\n", t.ID(), rel)
		}
	}
	return stale, nil
}

// generated returns each generated file of a task; a nil value means the
// file must not exist.
func generated(evalsDir string, t *spec.Task) (map[string][]byte, error) {
	files := map[string][]byte{}
	var df strings.Builder
	df.WriteString(generatedHeader)
	df.WriteString("# The agent's environment: the task's starting project in /app on the evals base image.\n")
	df.WriteString("FROM " + baseImage + "\n")
	overlay := filepath.Join(t.Dir, "environment", "workspace")
	if t.Meta.Workspace == "common" {
		df.WriteString("RUN project-setup common\n")
	}
	if isDir(overlay) {
		df.WriteString("COPY workspace/ /app/\n")
	} else if t.Meta.Workspace == "none" {
		return nil, fmt.Errorf("tasks/%s: workspace = \"none\" needs environment/workspace (the starting files)", t.ID())
	}
	df.WriteString("# The runner adds a condition's agent aids (--agents-md, --skills) to the next line.\n")
	df.WriteString(conditionMarker + "\n")
	files["environment/Dockerfile"] = []byte(df.String())

	images, err := appImages(evalsDir)
	if err != nil {
		return nil, err
	}
	compose := composeFile(t, images)
	files["environment/docker-compose.yaml"] = compose
	files["tests/docker-compose.yaml"] = compose
	files["tests/Dockerfile"] = []byte(generatedHeader +
		"# The verifier's environment: a fresh container (the agent's /app is copied in as an artifact).\n" +
		"FROM " + verifierImage + "\nCOPY . /tests/\n")
	files["tests/test.sh"] = []byte("#!/usr/bin/env bash\n" + generatedHeader +
		"# Checks the agent's project (see README.md, \"How a task is verified\").\n" +
		"exec /opt/evals/bin/evals-verify --tests /tests --workspace /app --out /logs/verifier\n")

	m := manifest.Manifest{}
	var initialConfig []byte
	if t.Meta.Workspace == "common" {
		common := filepath.Join(evalsDir, "workspace")
		if err := manifest.Add(m, common, ""); err != nil {
			return nil, err
		}
		initialConfig, _ = os.ReadFile(filepath.Join(common, "axx.yaml"))
	}
	if isDir(overlay) {
		if err := manifest.Add(m, overlay, ""); err != nil {
			return nil, err
		}
	}
	if b, err := os.ReadFile(filepath.Join(overlay, "axx.yaml")); err == nil {
		initialConfig = b
	}
	files["tests/initial.sha256"] = m.Bytes()
	files["tests/initial/axx.yaml"] = initialConfig // nil: no initial axx.yaml
	if t.PlainDir != "" {
		if err := plainFiles(evalsDir, t, files); err != nil {
			return nil, err
		}
	}
	return files, nil
}

// plainExcluded are the parts of the common starting project that are axx's;
// the starting project without axx leaves them out (and so does
// `project-setup plain`).
var plainExcluded = []string{"axx.yaml", "axx-packs.yaml", "features", "seeds"}

// plainFiles adds the generated files of a task's version without axx
// (plain/): the task.toml, the environment, the verifier's files and the
// starting project's manifest. The instruction, tests/verify.toml and the
// solution are written by hand.
func plainFiles(evalsDir string, t *spec.Task, files map[string][]byte) error {
	if t.Meta.Workspace != "common" || isDir(filepath.Join(t.Dir, "environment", "workspace")) {
		return fmt.Errorf("tasks/%s: a version without axx needs the common starting project, without an overlay", t.ID())
	}
	tt, err := os.ReadFile(filepath.Join(t.Dir, "task.toml"))
	if err != nil {
		return err
	}
	name := "name = \"" + t.Name + "\""
	if !bytes.Contains(tt, []byte(name)) {
		return fmt.Errorf("tasks/%s/task.toml: no line %s", t.ID(), name)
	}
	files["plain/task.toml"] = append([]byte("# Generated by `go run ./cmd/evals sync` from ../task.toml: the task without axx; do not edit.\n"),
		bytes.Replace(tt, []byte(name), []byte("name = \""+t.Name+"-plain\""), 1)...)
	files["plain/environment/Dockerfile"] = []byte(generatedHeader +
		"# The agent's environment without axx: the starting project without axx's files, and no axx.\n" +
		"FROM " + baseImage + "\nRUN project-setup plain\n")
	files["plain/environment/docker-compose.yaml"] = files["environment/docker-compose.yaml"]
	files["plain/tests/docker-compose.yaml"] = files["tests/docker-compose.yaml"]
	files["plain/tests/Dockerfile"] = files["tests/Dockerfile"]
	files["plain/tests/test.sh"] = files["tests/test.sh"]
	m, err := plainManifest(evalsDir)
	if err != nil {
		return err
	}
	files["plain/tests/initial.sha256"] = m.Bytes()
	return nil
}

// plainManifest is the starting project without axx: the common one minus
// plainExcluded, plus workspace-plain/.
func plainManifest(evalsDir string) (manifest.Manifest, error) {
	m := manifest.Manifest{}
	if err := manifest.Add(m, filepath.Join(evalsDir, "workspace"), ""); err != nil {
		return nil, err
	}
	for p := range m {
		if slices.Contains(plainExcluded, strings.SplitN(p, "/", 2)[0]) {
			delete(m, p)
		}
	}
	if err := manifest.Add(m, filepath.Join(evalsDir, "workspace-plain"), ""); err != nil {
		return nil, err
	}
	return m, nil
}

// appImages returns the image of each service in app/compose.yaml, where
// Renovate keeps them current: the tasks' sidecars use the same ones.
func appImages(evalsDir string) (map[string]string, error) {
	b, err := os.ReadFile(filepath.Join(evalsDir, "app", "compose.yaml"))
	if err != nil {
		return nil, err
	}
	var c struct {
		Services map[string]struct {
			Image string `yaml:"image"`
		} `yaml:"services"`
	}
	if err := yaml.Unmarshal(b, &c); err != nil {
		return nil, fmt.Errorf("app/compose.yaml: %w", err)
	}
	images := map[string]string{"address-service": addressImage}
	for _, s := range []string{"postgres", "mongo", "kafka", "schema-registry"} {
		img := c.Services[s].Image
		if img == "" {
			return nil, fmt.Errorf("app/compose.yaml: service %s has no image", s)
		}
		images[s] = img
	}
	return images, nil
}

// composeFile is the sidecar infrastructure of a task (the same for the agent
// and the verifier environment; Harbor adds the main container), with the
// images of app/compose.yaml.
func composeFile(t *spec.Task, images map[string]string) []byte {
	var b strings.Builder
	b.WriteString(generatedHeader)
	b.WriteString("# Infrastructure next to the main container (Harbor defines main itself).\nservices:\n  main:\n")
	if t.HasService("kafka") {
		b.WriteString("    environment:\n      PARCELS_KAFKA_BROKERS: kafka:9092\n")
	}
	b.WriteString("    depends_on:\n")
	for _, s := range t.Meta.Services {
		fmt.Fprintf(&b, "      %s:\n        condition: service_healthy\n", s)
		if s == "kafka" {
			b.WriteString("      schema-registry:\n        condition: service_healthy\n")
		}
	}
	for _, s := range t.Meta.Services {
		b.WriteString(imagePattern.ReplaceAllStringFunc(sidecars[s], func(m string) string {
			return "image: " + images[imagePattern.FindStringSubmatch(m)[1]]
		}))
	}
	return []byte(b.String())
}

